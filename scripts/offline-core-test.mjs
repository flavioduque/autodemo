import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript/lib/typescript.js');
const src=fs.readFileSync('packages/core/src/index.ts','utf8');
const js=ts.transpileModule(src,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const url='data:text/javascript;base64,'+Buffer.from(js).toString('base64');
const {buildAutoZooms}=await import(url);
const a=(o={})=>({id:'x',type:'click',atMs:1000,durationMs:20,x:.5,y:.5,...o});
let z=buildAutoZooms([a()],5000);
if(z.length!==1||z[0].fromMs!==780||z[0].toMs!==2200||z[0].scale!==1.36) throw new Error('single zoom test failed');
z=buildAutoZooms([a({atMs:1000,x:.5,y:.5}),a({atMs:1500,x:.54,y:.52})],5000);
if(z.length!==1||z[0].toMs<2700) throw new Error('merge zoom test failed');
z=buildAutoZooms([a({x:undefined,y:undefined})],5000);
if(z.length!==0) throw new Error('missing coordinates test failed');
console.log('Core auto-zoom tests passed: 3/3');
